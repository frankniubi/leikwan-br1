import pathlib,runpy,json,datetime,collections
m=runpy.run_path(str(pathlib.Path(__file__).with_name('jp-uot-recon.py')))
root=m['ROOT'];c=m['connect']('172.21.255.189')
try:
    result=json.loads((root/'tmp/jp-uot-canary-20260916/result.json').read_text())
    start=datetime.datetime.fromtimestamp(result['started'],datetime.timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')
    end=datetime.datetime.fromtimestamp(result['ended'],datetime.timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')
    logs=m['run'](c,f"journalctl -u leikwan-client-agent --since '{start}' --until '{end}' --no-pager -o cat | grep -E 'Ultra lease|Ultra renewal|renewal delivered' || true")
    runtime=m['run'](c,f"journalctl -u ultra-forward-170 --since '{start}' --until '{end}' --no-pager -o cat | grep -E 'no_healthy_candidate|runtime stopped' || true")
    (root/'tmp/jp-uot-canary-20260916/renewals.txt').write_text(logs)
    (root/'tmp/jp-uot-canary-20260916/runtime-errors.txt').write_text(runtime)
    print(json.dumps({'lease_log_lines':len(logs.splitlines()),'runtime_error_lines':len(runtime.splitlines()),'examples':logs.splitlines()[:8]}))
    sockets=m['run'](c,"ss -ntp state established '( dport = :5438 )'")
    (root/'tmp/jp-uot-pipeline-20260916/provider-sockets.txt').write_text(sockets)
    print(sockets)
finally:c.close()
